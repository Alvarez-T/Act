using System.Collections.Generic;
using System.Globalization;
using System.Linq;
using System.Text;
using Microsoft.CodeAnalysis;

namespace YFex.Validation.Generator;

/// <summary>
/// Emits the IValidatable implementation for one type (03 §2). StringBuilder only.
/// Member chains stop at the first Error; Warning/Info rules don't stop the chain.
/// </summary>
internal static partial class Emitter
{
    private const string W = "global::YFex.Validation.ViolationWriter";
    private const string FP = "global::YFex.FieldPath";
    private const string FC = "global::YFex.Validation.FieldConstraints";
    private const string Profile = "global::YFex.Validation.ProfileId";
    private const string Checks = "global::YFex.Validation.BuiltIn.Checks";
    private const string Mem = "global::System.MemoryExtensions";

    public static void Emit(SourceProductionContext spc, TypeModel model)
    {
        if (!model.CanEmit) return;
        spc.AddSource(model.HintName, model.Vm is null ? Render(model) : RenderVm(model));
    }

    internal static string Render(TypeModel m)
    {
        var sb = new Sb();
        sb.Line("// <auto-generated/>");
        sb.Line("#nullable enable");
        sb.Line("#pragma warning disable CS1591 // generated members are self-describing");
        sb.Line();

        if (m.Namespace.Length > 0)
        {
            sb.Line("namespace " + m.Namespace);
            sb.Open();
        }
        foreach (var c in m.Containers)
        {
            sb.Line("partial " + c.Keyword + " " + c.NameWithTypeParameters);
            sb.Open();
        }

        string self = m.NameWithTypeParameters;
        string newMod = m.BaseValidatableFqn is null ? "" : "new ";

        sb.Line("[global::System.CodeDom.Compiler.GeneratedCode(\"YFex.Validation.Generator\", \"1.0.0\")]");
        sb.Line($"partial {m.Keyword} {self} : global::YFex.Validation.IValidatable<{self}>");
        sb.Open();

        EmitFieldIds(sb, m, newMod);
        EmitFields(sb, m, newMod);
        EmitRules(sb, m, newMod);
        EmitInvariantIds(sb, m, newMod);
        EmitMemberMethods(sb, m, self);
        EmitValidate(sb, m, self, newMod);
        EmitValidateMember(sb, m, self, newMod);
        EmitTryGetConstraints(sb, m, self, newMod);
        EmitTryGetFieldId(sb, m, newMod);
        EmitCoerce(sb, m, self);
        EmitShape(sb, m, newMod);

        sb.Close();
        foreach (var _ in m.Containers) sb.Close();
        if (m.Namespace.Length > 0) sb.Close();
        return sb.ToString();
    }

    // ── Nested metadata classes ──────────────────────────────────────────────────

    private static void EmitFieldIds(Sb sb, TypeModel m, string newMod)
    {
        sb.Line("/// <summary>Member ids — dense, declaration order.</summary>");
        sb.Line($"public {newMod}static class {m.FieldIdsClass}");
        sb.Open();
        foreach (var mem in m.Members)
            sb.Line($"public const ushort {mem.Name} = {mem.Id};");
        sb.Close();
        sb.Line();
    }

    private static void EmitFields(Sb sb, TypeModel m, string newMod)
    {
        sb.Line("/// <summary>Ready-made paths (no allocation when adding violations).</summary>");
        sb.Line($"public {newMod}static class {m.FieldsClass}");
        sb.Open();
        foreach (var mem in m.Members)
            sb.Line($"public static readonly {FP} {mem.Name} = {FP}.Of({Parser.Literal(mem.Name)});");
        sb.Close();
        sb.Line();
    }

    private static void EmitRules(Sb sb, TypeModel m, string newMod)
    {
        sb.Line("/// <summary>Per-member metadata and checks (every member has a class, even without rules).</summary>");
        sb.Line($"public {newMod}static class {m.RulesClass}");
        sb.Open();
        foreach (var mem in m.Members)
        {
            sb.Line($"public static class {mem.Name}");
            sb.Open();

            EmitConsts(sb, mem.Rules.Where(r => !r.IsConditional).ToList(), mem.HasAsyncRules);
            EmitRuleFields(sb, mem.Rules, "");
            sb.Line($"public static {FC} Constraints {{ get; }} = {ConstraintsExpr(mem.Rules, "")};");

            // Check: the unconditional chain for one value (other generators call it by convention).
            sb.Line($"public static bool Check({mem.CheckParamType} value, ref {W} w, in {FP} path)");
            sb.Open();
            var target = new Target(mem.Shape, mem.Collection, mem.IsReferenceType, mem.IsNullableValue);
            for (int i = 0; i < mem.Rules.Length; i++)
                if (!mem.Rules[i].IsConditional)
                    EmitRule(sb, mem.Rules[i], i, "", "value", "path", target, guard: null, fieldPrefix: "");
            sb.Line("return true;");
            sb.Close();

            // Check + profile: also runs Profile-scoped rules (When rules need the owner and stay out). VMs borrow
            // through this overload by convention (07 §4.4) — emitted for every member.
            sb.Line($"public static bool Check({mem.CheckParamType} value, ref {W} w, in {FP} path, {Profile} profile)");
            sb.Open();
            for (int i = 0; i < mem.Rules.Length; i++)
            {
                var r = mem.Rules[i];
                if (!r.IsConditional)
                    EmitRule(sb, r, i, "", "value", "path", target, guard: null, fieldPrefix: "");
                else if (r.When is null)
                    EmitRule(sb, r, i, "", "value", "path", target, guard: $"profile.Includes({Parser.Literal(r.Profile!)})", fieldPrefix: "");
            }
            sb.Line("return true;");
            sb.Close();

            if (mem.Each is { } each)
            {
                EmitRuleFields(sb, each.ElementRules, "Item");
                sb.Line($"public static readonly {FP} ItemPath = {FP}.Of({Parser.Literal(mem.Name + "[]")});");
                sb.Line($"public static {FC} ItemConstraints {{ get; }} = {ConstraintsExpr(each.ElementRules, "Item")};");
                sb.Line($"public static bool CheckItem({ElementParam(each)} value, ref {W} w, in {FP} path)");
                sb.Open();
                var et = new Target(each.ElementShape, CollectionKind.None, each.ElementIsReferenceType, each.ElementIsNullableValue);
                for (int i = 0; i < each.ElementRules.Length; i++)
                    if (!each.ElementRules[i].IsConditional)
                        EmitRule(sb, each.ElementRules[i], i, "Item", "value", "path", et, guard: null, fieldPrefix: "");
                sb.Line("return true;");
                sb.Close();
            }

            foreach (var (r, i) in mem.Rules.Select((r, i) => (r, i)))
                if (r.Kind == RuleKind.Range && r.Coerce && r.BoundsTypeFqn is not null)
                    sb.Line($"public static {mem.TypeFqn} Coerce({mem.TypeFqn} value) => {CoerceExpr(r, i, "", mem.IsNullableValue)};");

            sb.Close();
        }
        sb.Close();
        sb.Line();
    }

    private static void EmitConsts(Sb sb, List<RuleModel> rules, bool hasAsync)
    {
        if (rules.Any(r => r.Kind == RuleKind.Required && r.IsError)) sb.Line("public const bool Required = true;");
        if (rules.FirstOrDefault(r => r.Kind == RuleKind.Length) is { } len)
        {
            if (len.MinLength > 0) sb.Line($"public const int MinLength = {len.MinLength};");
            if (len.MaxLength != int.MaxValue) sb.Line($"public const int MaxLength = {len.MaxLength};");
        }
        if (rules.FirstOrDefault(r => r.Kind == RuleKind.Range && r.MinConstLiteral is not null) is { } range)
        {
            string t = range.BoundsTypeFqn!;
            sb.Line($"public const {t} Min = {range.MinConstLiteral};");
            sb.Line($"public const {t} Max = {range.MaxConstLiteral};");
        }
        if (hasAsync) sb.Line("public const bool HasAsyncRules = true;");
    }

    // Static fields for non-literal range bounds and patterns. Declared before Constraints (initializer order).
    private static void EmitRuleFields(Sb sb, EquatableArray<RuleModel> rules, string prefix)
    {
        for (int i = 0; i < rules.Length; i++)
        {
            var r = rules[i];
            if (r.Kind == RuleKind.Range && !r.UsesOperators && r.BoundsTypeFqn is not null)
            {
                sb.Line($"internal static readonly {r.BoundsTypeFqn} __{prefix}Min_{i} = {r.MinExpr};");
                sb.Line($"internal static readonly {r.BoundsTypeFqn} __{prefix}Max_{i} = {r.MaxExpr};");
            }
            else if (r.Kind == RuleKind.Pattern)
            {
                sb.Line($"internal static readonly global::System.Text.RegularExpressions.Regex __{prefix}Pattern_{i} = new({Parser.Literal(r.Pattern!)}, " +
                        "global::System.Text.RegularExpressions.RegexOptions.CultureInvariant, global::System.TimeSpan.FromSeconds(1));");
            }
        }
    }

    /// <summary>Constraints from the unconditional rules of a member (conditional rules can't be shown statically).</summary>
    private static string ConstraintsExpr(EquatableArray<RuleModel> all, string prefix)
    {
        var args = new List<string>();
        bool any = false, anyError = false, anyWarning = false;
        bool length = false, range = false, format = false;
        for (int i = 0; i < all.Length; i++)
        {
            var r = all[i];
            if (r.IsConditional || r.Kind == RuleKind.AsyncValueRule) continue;
            any = true;
            anyError |= r.IsError;
            anyWarning |= r.SeverityExpr.EndsWith(".Warning", System.StringComparison.Ordinal);
            switch (r.Kind)
            {
                case RuleKind.Required when r.IsError:
                    args.Add("required: true");
                    break;
                case RuleKind.NotEmpty when r.IsError && !length && !all.AsSpan().ToArray().Any(x => x.Kind == RuleKind.Length && !x.IsConditional):
                    length = true;
                    args.Add("minLength: 1");
                    break;
                case RuleKind.Length when !length:
                    length = true;
                    if (r.MinLength > 0) args.Add("minLength: " + r.MinLength.ToString(CultureInfo.InvariantCulture));
                    if (r.MaxLength != int.MaxValue) args.Add("maxLength: " + r.MaxLength.ToString(CultureInfo.InvariantCulture));
                    break;
                case RuleKind.Range when !range && r.MinRawExpr is not null:
                    range = true;
                    args.Add("min: " + Raw(r.MinRawExpr, "__" + prefix, i));
                    args.Add("max: " + Raw(r.MaxRawExpr!, "__" + prefix, i));
                    break;
                case RuleKind.Email or RuleKind.TextRule when !format:
                    format = true;
                    args.Add("format: " + r.CodeExpr);
                    break;
            }
        }
        if (!any) return "default";
        args.Add("maxSeverity: global::YFex.Validation.Severity." + (anyError ? "Error" : anyWarning ? "Warning" : "Info"));
        return $"{FC}.Create({string.Join(", ", args)})";
    }

    /// <summary>Resolves the __MIN__/__MAX__ placeholders of a non-literal bound to its static field.</summary>
    private static string Raw(string raw, string qualifier, int index)
        => raw.Replace("__MIN__", $"{qualifier}Min_{index}").Replace("__MAX__", $"{qualifier}Max_{index}");

    private static void EmitInvariantIds(Sb sb, TypeModel m, string newMod)
    {
        if (m.Invariants.IsEmpty) return;
        sb.Line("/// <summary>Invariant ids (OwnerId in ViolationOrigin).</summary>");
        sb.Line($"public {newMod}static class {m.InvariantIdsClass}");
        sb.Open();
        foreach (var inv in m.Invariants)
            sb.Line($"public const ushort {inv.MethodName} = {inv.Id};");
        sb.Close();
        foreach (var inv in m.Invariants)
        {
            string ids = string.Join(", ", inv.Reads.Select(r => $"{m.FieldIdsClass}.{r}"));
            sb.Line($"internal static global::System.ReadOnlySpan<ushort> __Reads_{inv.MethodName} => new ushort[] {{ {ids} }};");
        }
        sb.Line();
    }

    // ── Owner-aware member validation (conditional rules, [Each], nested) ────────

    private static bool NeedsMemberMethod(MemberModel mem)
        => mem.Each is not null || mem.NestedValidatableFqn is not null || mem.Rules.Any(r => r.IsConditional);

    private static string MemberCall(TypeModel m, MemberModel mem, string profileExpr)
        => NeedsMemberMethod(mem)
            ? $"__Validate_{mem.Name}(in v, ref w, {profileExpr})"
            : $"{m.RulesClass}.{mem.Name}.Check(v.{mem.Name}, ref w, in {m.FieldsClass}.{mem.Name})";

    private static void EmitMemberMethods(Sb sb, TypeModel m, string self)
    {
        foreach (var mem in m.Members)
        {
            if (!NeedsMemberMethod(mem)) continue;
            string rules = $"{m.RulesClass}.{mem.Name}";
            string path = $"{m.FieldsClass}.{mem.Name}";

            sb.Line($"private static bool __Validate_{mem.Name}(in {self} v, ref {W} w, {Profile} profile)");
            sb.Open();
            sb.Line($"var __m = v.{mem.Name};");
            var target = new Target(mem.Shape, mem.Collection, mem.IsReferenceType, mem.IsNullableValue);
            for (int i = 0; i < mem.Rules.Length; i++)
                EmitRule(sb, mem.Rules[i], i, "", "__m", path, target, Guard(mem.Rules[i]), fieldPrefix: rules + ".");

            if (mem.Each is { } each)
            {
                sb.Line("int __before = w.ErrorCount;");
                EmitEachLoop(sb, m, mem, each, rules);
                sb.Line("return w.ErrorCount == __before;");
            }
            else if (mem.NestedValidatableFqn is { } nested)
            {
                sb.Line(mem.NestedIsNullable
                    ? $"if (__m is {{ }} __n) return global::YFex.Validation.Validator.ValidateAt<{nested}>(in __n, ref w, in {path});"
                    : $"return global::YFex.Validation.Validator.ValidateAt<{nested}>(in __m, ref w, in {path});");
                if (mem.NestedIsNullable) sb.Line("return true;");
            }
            else
            {
                sb.Line("return true;");
            }
            sb.Close();
            sb.Line();

            if (mem.Each is { ElementRules.IsEmpty: false } e2)
            {
                sb.Line($"private static bool __ValidateItem_{mem.Name}(in {self} v, {ElementParam(e2)} value, ref {W} w, in {FP} path, {Profile} profile)");
                sb.Open();
                var et = new Target(e2.ElementShape, CollectionKind.None, e2.ElementIsReferenceType, e2.ElementIsNullableValue);
                for (int i = 0; i < e2.ElementRules.Length; i++)
                    EmitRule(sb, e2.ElementRules[i], i, "Item", "value", "path", et, Guard(e2.ElementRules[i]), fieldPrefix: rules + ".");
                sb.Line("return true;");
                sb.Close();
                sb.Line();
            }
        }
    }

    private static void EmitEachLoop(Sb sb, TypeModel m, MemberModel mem, EachModel each, string rules)
    {
        string open = mem.Collection switch
        {
            CollectionKind.ImmutableArray when mem.IsNullableValue => "if (__m is { IsDefault: false } __c)",
            CollectionKind.ImmutableArray => "if (!__m.IsDefault)",
            _ => "if (__m is { } __c)",
        };
        sb.Line(open);
        sb.Open();
        if (mem.Collection == CollectionKind.ImmutableArray && !mem.IsNullableValue) sb.Line("var __c = __m;");
        string count;
        switch (mem.Collection)
        {
            case CollectionKind.List:
                sb.Line("var __s = global::System.Runtime.InteropServices.CollectionsMarshal.AsSpan(__c);");
                count = "__s.Length";
                break;
            case CollectionKind.IndexedList:
                count = "__c.Count";
                break;
            default:
                count = "__c.Length";
                break;
        }
        sb.Line($"for (int __i = 0; __i < {count}; __i++)");
        sb.Open();
        sb.Line($"var __p = {rules}.ItemPath.WithIndex(__i);");
        sb.Line(mem.Collection switch
        {
            CollectionKind.Array => "ref readonly var __e = ref __c[__i];",
            CollectionKind.ImmutableArray => "ref readonly var __e = ref __c.ItemRef(__i);",
            CollectionKind.List => "ref readonly var __e = ref __s[__i];",
            _ => "var __e = __c[__i];",
        });
        if (!each.ElementRules.IsEmpty)
            sb.Line($"__ValidateItem_{mem.Name}(in v, __e, ref w, in __p, profile);");
        if (each.ElementValidatableFqn is { } ev)
        {
            string call = $"global::YFex.Validation.Validator.ValidateAt<{ev}>(in __ev, ref w, in __p);";
            if (each.ElementIsReferenceType || each.ElementIsNullableValue)
                sb.Line($"if (__e is {{ }} __ev) {call}");
            else
                sb.Line($"global::YFex.Validation.Validator.ValidateAt<{ev}>(in __e, ref w, in __p);");
        }
        sb.Close();
        sb.Close();
    }

    private static string? Guard(RuleModel r)
    {
        var parts = new List<string>();
        if (r.When is not null) parts.Add("v." + r.When);
        if (r.Profile is not null) parts.Add($"profile.Includes({Parser.Literal(r.Profile)})");
        return parts.Count == 0 ? null : string.Join(" && ", parts);
    }

    // ── Rule check emission ──────────────────────────────────────────────────────

    private readonly struct Target
    {
        public Target(MemberShape shape, CollectionKind collection, bool isReference, bool isNullableValue)
        {
            Shape = shape;
            Collection = collection;
            IsReference = isReference;
            IsNullableValue = isNullableValue;
        }

        public MemberShape Shape { get; }
        public CollectionKind Collection { get; }
        public bool IsReference { get; }
        public bool IsNullableValue { get; }
    }

    private static void EmitRule(Sb sb, RuleModel r, int index, string prefix, string v, string path,
        Target t, string? guard, string fieldPrefix)
    {
        string? cond = FailCondition(r, index, prefix, v, t, fieldPrefix);
        if (cond is null) return;

        string add = $"w.Add(in {path}, {r.CodeExpr}{Args(r, index, prefix, fieldPrefix)}, {r.SeverityExpr});";
        string stmt = r.IsError ? $"{{ {add} return false; }}" : add;
        sb.Line(guard is null ? $"if ({cond}) {stmt}" : $"if ({guard} && ({cond})) {stmt}");
    }

    private static string Args(RuleModel r, int index, string prefix, string fieldPrefix)
    {
        switch (r.Kind)
        {
            case RuleKind.Length:
                string min = $"global::YFex.RawValue.From({r.MinLength})";
                string max = $"global::YFex.RawValue.From({r.MaxLength})";
                if (r.MaxLength == int.MaxValue) return ", " + min;
                if (r.MinLength == 0) return ", " + max;
                return $", {min}, {max}";
            case RuleKind.Range when r.MinRawExpr is not null:
                return ", " + Raw(r.MinRawExpr, fieldPrefix + "__" + prefix, index)
                     + ", " + Raw(r.MaxRawExpr!, fieldPrefix + "__" + prefix, index);
            case RuleKind.TextRule or RuleKind.ValueRule when r.ArgumentRawExpr is not null:
                return ", " + r.ArgumentRawExpr;
            default:
                return "";
        }
    }

    private static string? FailCondition(RuleModel r, int index, string prefix, string v, Target t, string fieldPrefix)
    {
        switch (r.Kind)
        {
            case RuleKind.Required:
            case RuleKind.NotEmpty:
                return Presence(r.Kind == RuleKind.Required, v, t);

            case RuleKind.Length:
            {
                string within(string len) => $"!{Checks}.LengthWithin({len}, {r.MinLength}, {r.MaxLength})";
                if (t.Shape == MemberShape.String) return $"{v} is not null && {within(v + ".Length")}";
                return t.Collection switch
                {
                    CollectionKind.ImmutableArray when t.IsNullableValue => $"{v} is {{ IsDefault: false }} __l && {within("__l.Length")}",
                    CollectionKind.ImmutableArray => $"!{v}.IsDefault && {within(v + ".Length")}",
                    CollectionKind.Array => $"{v} is not null && {within(v + ".Length")}",
                    _ => $"{v} is not null && {within(v + ".Count")}",
                };
            }

            case RuleKind.Range:
            {
                if (r.Coerce) return null; // clamped by the pipeline (Rules.X.Coerce), never a violation
                string minE = r.UsesOperators ? r.MinExpr! : $"{fieldPrefix}__{prefix}Min_{index}";
                string maxE = r.UsesOperators ? r.MaxExpr! : $"{fieldPrefix}__{prefix}Max_{index}";
                string test(string x) => r.UsesOperators
                    ? $"{x} < {minE} || {x} > {maxE}"
                    : $"!{Checks}.Within({x}, {minE}, {maxE})";
                if (t.IsNullableValue) return $"{v} is {{ }} __r && ({test("__r")})";
                if (t.IsReference) return $"{v} is not null && ({test(v)})";
                return test(v);
            }

            case RuleKind.Pattern:
                return $"!string.IsNullOrEmpty({v}) && !{fieldPrefix}__{prefix}Pattern_{index}.IsMatch({v})";

            case RuleKind.Email:
                return $"!string.IsNullOrEmpty({v}) && !global::YFex.Validation.BuiltIn.Email.IsValid({v})";

            case RuleKind.TextRule:
                return $"!string.IsNullOrEmpty({v}) && !{r.RuleTypeFqn}.IsValid({v}{(r.HasArgument ? ", " + r.ArgumentExpr : "")})";

            case RuleKind.ValueRule:
            {
                string call(string x) => $"!{r.RuleTypeFqn}.IsValid({x}{(r.HasArgument ? ", " + r.ArgumentExpr : "")})";
                if (t.IsNullableValue) return $"{v} is {{ }} __vr && {call("__vr")}";
                if (t.IsReference) return $"{v} is not null && {call(v)}";
                return call(v);
            }
        }
        return null;
    }

    private static string Presence(bool required, string v, Target t)
    {
        if (t.Shape == MemberShape.String)
            return required ? $"string.IsNullOrWhiteSpace({v})" : $"string.IsNullOrEmpty({v})";
        if (t.Shape == MemberShape.Collection)
        {
            return t.Collection switch
            {
                CollectionKind.ImmutableArray when t.IsNullableValue => $"{v} is not {{ IsDefaultOrEmpty: false }}",
                CollectionKind.ImmutableArray => $"{v}.IsDefaultOrEmpty",
                CollectionKind.Array => $"{v} is null || {v}.Length == 0",
                _ => $"{v} is null || {v}.Count == 0",
            };
        }
        if (t.IsNullableValue) return $"!{v}.HasValue";
        if (t.IsReference) return $"{v} is null";
        return $"{Checks}.IsDefault({v})";
    }

    private static string CoerceExpr(RuleModel r, int index, string prefix, bool nullable)
    {
        string minE = r.UsesOperators ? r.MinExpr! : $"__{prefix}Min_{index}";
        string maxE = r.UsesOperators ? r.MaxExpr! : $"__{prefix}Max_{index}";
        return nullable
            ? $"value is {{ }} __c ? {Checks}.Clamp(__c, {minE}, {maxE}) : value"
            : $"{Checks}.Clamp(value, {minE}, {maxE})";
    }

    private static string ElementParam(EachModel each)
        => each.ElementIsReferenceType && !each.ElementFqn.EndsWith("?") ? each.ElementFqn + "?" : each.ElementFqn;

    // ── Validate / ValidateMember / TryGetConstraints / TryGetFieldId ────────────

    private static void EmitValidate(Sb sb, TypeModel m, string self, string newMod)
    {
        sb.Line("/// <summary>Runs every member rule, then invariants and runtime rules; true when no Error was added.</summary>");
        // Validate / ValidateAt / ValidateMember overload (not hide) the base versions: different parameter types.
        sb.Line($"public static bool Validate(in {self} v, ref {W} w) => Validate(in v, ref w, default);");
        sb.Line();
        sb.Line("/// <summary>Validate for a profile: rules scoped to other profiles are skipped (<c>default</c> = all).</summary>");
        sb.Line($"public static bool Validate(in {self} v, ref {W} w, {Profile} profile)");
        sb.Open();
        sb.Line("int __errorsBefore = w.ErrorCount;");
        if (m.BaseValidatableFqn is { } b) sb.Line($"{b}.Validate(v, ref w, profile);");
        foreach (var mem in m.Members)
            sb.Line(MemberCall(m, mem, "profile") + ";");

        foreach (var inv in m.Invariants)
        {
            var gates = inv.ReadsAll ? new List<string>() : inv.Reads.Select(r => $"!w.HasErrorFor(in {m.FieldsClass}.{r})").ToList();
            if (gates.Count > 0) sb.Line($"if ({string.Join(" && ", gates)})");
            sb.Open();
            sb.Line("var __prevOrigin = w.CurrentOrigin;");
            sb.Line($"w.CurrentOrigin = new global::YFex.Validation.ViolationOrigin(global::YFex.Validation.ViolationSource.Invariant, {m.InvariantIdsClass}.{inv.MethodName});");
            sb.Line(inv.IsStatic ? $"{inv.MethodName}(v, ref w);" : $"v.{inv.MethodName}(ref w);");
            sb.Line("w.CurrentOrigin = __prevOrigin;");
            sb.Close();
        }

        sb.Line($"global::YFex.Validation.RuntimeRules<{self}>.Run(in v, ref w);");
        sb.Line("return w.ErrorCount == __errorsBefore;");
        sb.Close();
        sb.Line();
        sb.Line("/// <summary>Validate with every path placed under <paramref name=\"prefix\"/> (nested / element use).</summary>");
        sb.Line($"public static bool ValidateAt(in {self} v, ref {W} w, in {FP} prefix)");
        sb.Line($"    => global::YFex.Validation.Validator.ValidateAt<{self}>(in v, ref w, in prefix);");
        sb.Line();
    }

    private static void EmitValidateMember(Sb sb, TypeModel m, string self, string newMod)
    {
        sb.Line("/// <summary>Runs the rules of ONE member (no invariants).</summary>");
        sb.Line($"public static bool ValidateMember(global::YFex.Validation.FieldId member, in {self} v, ref {W} w)");
        sb.Open();
        sb.Line("switch (member.Value)");
        sb.Open();
        foreach (var mem in m.Members)
            sb.Line($"case {m.FieldIdsClass}.{mem.Name}: return {MemberCall(m, mem, "default")};");
        sb.Close();
        sb.Line(m.BaseValidatableFqn is { } b ? $"return {b}.ValidateMember(member, v, ref w);" : "return true;");
        sb.Close();
        sb.Line();
    }

    private static void EmitTryGetConstraints(Sb sb, TypeModel m, string self, string newMod)
    {
        sb.Line("/// <summary>Constraints of the member at <paramref name=\"path\"/> (nested and element paths delegate).</summary>");
        sb.Line($"public {newMod}static bool TryGetConstraints(global::System.ReadOnlySpan<char> path, out {FC} constraints)");
        sb.Open();
        if (!m.Members.IsEmpty)
        {
            sb.Line("switch (path)");
            sb.Open();
            foreach (var mem in m.Members)
                sb.Line($"case {Parser.Literal(mem.Name)}: constraints = {m.RulesClass}.{mem.Name}.Constraints; return true;");
            sb.Close();
        }
        foreach (var mem in m.Members)
        {
            if (mem.NestedValidatableFqn is { } nested)
            {
                string prefix = mem.Name + ".";
                sb.Line($"if ({Mem}.StartsWith(path, {Parser.Literal(prefix)}))");
                sb.Line($"    return {nested}.TryGetConstraints(path.Slice({prefix.Length}), out constraints);");
            }
            else if (mem.Each is { } each)
            {
                string prefix = mem.Name + "[";
                sb.Line($"if ({Mem}.StartsWith(path, {Parser.Literal(prefix)}))");
                sb.Open();
                sb.Line($"int __close = {Mem}.IndexOf(path, ']');");
                sb.Line("if (__close > 0)");
                sb.Open();
                sb.Line("var __rest = path.Slice(__close + 1);");
                sb.Line($"if (__rest.IsEmpty) {{ constraints = {m.RulesClass}.{mem.Name}.ItemConstraints; return true; }}");
                if (each.ElementValidatableFqn is { } ev)
                    sb.Line($"if (__rest[0] == '.') return {ev}.TryGetConstraints(__rest.Slice(1), out constraints);");
                sb.Close();
                sb.Close();
            }
        }
        if (m.BaseValidatableFqn is { } b)
            sb.Line($"if ({b}.TryGetConstraints(path, out constraints)) return true;");
        sb.Line($"return global::YFex.Validation.RuntimeRules<{self}>.TryGetConstraints(path, out constraints);");
        sb.Close();
        sb.Line();
    }

    // Range(coerce: true) members → one type-level Coerce (IValidatable<T>.Coerce) built with `with`, so only records
    // and structs get it; the dispatchers apply it before the query cache key (09 §7).
    private static void EmitCoerce(Sb sb, TypeModel m, string self)
    {
        if (!(m.Keyword.StartsWith("record", System.StringComparison.Ordinal) || m.Keyword == "struct")) return;
        var assignments = new List<string>();
        foreach (var mem in m.Members)
        {
            if (mem.Each is not null) continue;
            if (mem.Rules.Any(r => r.Kind == RuleKind.Range && r.Coerce && r.BoundsTypeFqn is not null))
                assignments.Add($"{mem.Name} = {m.RulesClass}.{mem.Name}.Coerce(value.{mem.Name})");
        }
        if (assignments.Count == 0) return;
        sb.Line();
        sb.Line("/// <summary>Clamps every Range(coerce: true) member into its bounds.</summary>");
        sb.Line($"public static {self} Coerce(in {self} value) => value with {{ {string.Join(", ", assignments)} }};");
    }

    /// <summary>Phase 6: member shapes for JSON Schema export (<c>JsonSchemaWriter.ToJson&lt;T&gt;()</c>, AI tool parameters).</summary>
    private static void EmitShape(Sb sb, TypeModel m, string newMod)
    {
        var members = m.Members.AsSpan().ToArray().Where(x => x.Json is not null).Select(x => JsonShape.Expression(x.Name, x.Json!)).ToArray();
        string name = m.NameWithTypeParameters;
        int lt = name.IndexOf('<');
        if (lt >= 0) name = name.Substring(0, lt);
        string baseShape = m.BaseValidatableFqn is { } b ? $", baseShape: static () => {b}.Shape" : "";
        sb.Line("private static global::YFex.Validation.TypeShape? __yfexShape;");
        sb.Line("/// <summary>Member shapes (JSON Schema export).</summary>");
        sb.Line($"public {newMod}static global::YFex.Validation.TypeShape? Shape => __yfexShape ??= new global::YFex.Validation.TypeShape({Parser.Literal(name)},");
        sb.Line($"    [{string.Join(", ", members)}]{baseShape});");
    }

    private static void EmitTryGetFieldId(Sb sb, TypeModel m, string newMod)
    {
        sb.Line("/// <summary>Id of the member named <paramref name=\"path\"/>.</summary>");
        sb.Line($"public {newMod}static bool TryGetFieldId(global::System.ReadOnlySpan<char> path, out global::YFex.Validation.FieldId id)");
        sb.Open();
        if (!m.Members.IsEmpty)
        {
            sb.Line("switch (path)");
            sb.Open();
            foreach (var mem in m.Members)
                sb.Line($"case {Parser.Literal(mem.Name)}: id = new({m.FieldIdsClass}.{mem.Name}); return true;");
            sb.Close();
        }
        if (m.BaseValidatableFqn is { } b) sb.Line($"return {b}.TryGetFieldId(path, out id);");
        else
        {
            sb.Line("id = default;");
            sb.Line("return false;");
        }
        sb.Close();
    }

    // ── Module initializer (task 5) ──────────────────────────────────────────────

    public static void EmitModuleInitializer(SourceProductionContext spc, IReadOnlyList<TypeModel> models)
    {
        var registrable = models.Where(x => x.CanEmit && x.IsRegistrable).Select(x => x.FullyQualifiedName).Distinct().OrderBy(x => x, System.StringComparer.Ordinal).ToList();
        if (registrable.Count == 0) return;

        var sb = new Sb();
        sb.Line("// <auto-generated/>");
        sb.Line("#nullable enable");
        sb.Line("#pragma warning disable CA2255 // module initializers are the registration mechanism here");
        sb.Line();
        sb.Line("namespace YFex.Validation.Generated");
        sb.Open();
        sb.Line("[global::System.CodeDom.Compiler.GeneratedCode(\"YFex.Validation.Generator\", \"1.0.0\")]");
        sb.Line("internal static class ValidationModuleInitializer");
        sb.Open();
        sb.Line("/// <summary>Fills ValidationSlot&lt;T&gt; for every validatable type of this assembly (+ compiled fluent rule keys).</summary>");
        sb.Line("[global::System.Runtime.CompilerServices.ModuleInitializer]");
        sb.Line("internal static void Register()");
        sb.Open();
        foreach (var fqn in registrable)
            sb.Line($"global::YFex.Validation.ValidationSlots.Register<{fqn}>();");

        // D27: fluent rules compiled into T.Validate — the runtime ValidationBuilder<T> skips these keys.
        foreach (var m in models.Where(x => x.CanEmit && x.IsRegistrable && !x.CompiledFluentKeys.IsEmpty)
                     .OrderBy(x => x.FullyQualifiedName, System.StringComparer.Ordinal))
        {
            var keys = m.CompiledFluentKeys.AsSpan().ToArray().Distinct().OrderBy(k => k, System.StringComparer.Ordinal)
                .Select(k => Parser.Literal(k));
            sb.Line($"global::YFex.Validation.CompiledFluentRules<{m.FullyQualifiedName}>.Set({string.Join(", ", keys)});");
        }
        sb.Close();
        sb.Close();
        sb.Close();
        spc.AddSource("YFex.Validation.ModuleInitializer.g.cs", sb.ToString());
    }

    // ── Tiny indenting builder ───────────────────────────────────────────────────

    private sealed class Sb
    {
        private readonly StringBuilder _sb = new(4096);
        private int _indent;

        public void Line(string text = "")
        {
            if (text.Length > 0) _sb.Append(' ', _indent * 4).Append(text);
            _sb.Append('\n');
        }

        public void Open() { Line("{"); _indent++; }
        public void Close() { _indent--; Line("}"); }
        public override string ToString() => _sb.ToString();
    }
