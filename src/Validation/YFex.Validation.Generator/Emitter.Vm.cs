using System.Collections.Generic;
using System.Globalization;
using System.Linq;

namespace YFex.Validation.Generator;

/// <summary>
/// View-model emission (07 §3–8, D22): implements the State generator's <c>partial void</c> hooks, writing into
/// the per-object <c>ValidationBag</c>. Setting a valid value allocates nothing: the writer is on the stack and the
/// bag skips unchanged results.
/// </summary>
internal static partial class Emitter
{
    private const string Bag = "global::YFex.State.Validation.ValidationBag";
    private const string Source = "global::YFex.Validation.ViolationSource";
    private const string Violation = "global::YFex.Validation.Violation";
    private const string VSpan = "global::System.ReadOnlySpan<global::YFex.Validation.Violation>";
    private const string CharSpan = "global::System.ReadOnlySpan<char>";

    internal static string RenderVm(TypeModel m)
    {
        var vm = m.Vm!;
        var sb = new Sb();
        sb.Line("// <auto-generated/>");
        sb.Line("#nullable enable");
        sb.Line("#pragma warning disable CS1591 // generated members are self-describing");
        sb.Line("#pragma warning disable CS0618 // obsolete YFex.State validators are still honoured (one release)");
        sb.Line("#pragma warning disable CS0108, CS0109 // metadata classes/helpers intentionally hide a base view model's");
        sb.Line();
        if (m.Namespace.Length > 0)
        {
            sb.Line("namespace " + m.Namespace);
            sb.Open();
        }

        string self = m.NameWithTypeParameters;
        // No [GeneratedCode] here: the State generator's part of this class already carries one (CS0579).
        sb.Line($"partial class {self} : global::YFex.Validation.IValidationSource");
        sb.Open();

        EmitFieldIds(sb, m, "");
        EmitFields(sb, m, "");
        EmitRules(sb, m, "");
        EmitInvariantIds(sb, m, "");
        EmitMemberMethods(sb, m, self);

        EmitConfigure(sb, vm);
        EmitHooks(sb, m, vm);
        EmitFieldRunners(sb, m, vm);
        EmitAsyncRunners(sb, m, vm);
        EmitVmInvariants(sb, m, vm);
        EmitValidationSource(sb, m, vm);
        EmitValidateAll(sb, m, vm);
        EmitContracts(sb, m, vm);

        sb.Close();
        if (m.Namespace.Length > 0) sb.Close();
        return sb.ToString();
    }

    // ── Helpers over the model ───────────────────────────────────────────────────

    private static bool HasAsync(MemberModel mem, VmMemberModel v) => mem.HasAsyncRules || !v.LegacyAsync.IsEmpty;

    /// <summary>The member has field rules of any kind → gets a <c>__RunField_X</c>.</summary>
    private static bool IsValidated(MemberModel mem, VmMemberModel v)
        => !mem.Rules.IsEmpty || mem.Each is not null || mem.NestedValidatableFqn is not null || HasAsync(mem, v)
           || !v.Borrowed.IsEmpty || !v.LegacySync.IsEmpty;

    private static IEnumerable<(MemberModel Mem, VmMemberModel Vm)> Pairs(TypeModel m)
    {
        for (int i = 0; i < m.Members.Length; i++) yield return (m.Members[i], m.Vm!.Members[i]);
    }

    private static string Hex(ulong mask) => "0x" + mask.ToString("X", CultureInfo.InvariantCulture) + "UL";

    private static string ProfileGuard(string? profile) => profile is null ? "" : $"__profile.Includes({Parser.Literal(profile)})";

    // ── ConfigureValidation ([ValidationOptions], default profile) ───────────────

    private static void EmitConfigure(Sb sb, VmModel vm)
    {
        if (vm.ShowExpr is null && vm.DefaultProfile is null) return;
        sb.Line($"protected override void ConfigureValidation({Bag} bag)");
        sb.Open();
        sb.Line("base.ConfigureValidation(bag);");
        if (vm.ShowExpr is not null) sb.Line($"bag.Show = {vm.ShowExpr};");
        if (vm.DefaultProfile is not null) sb.Line($"bag.Profile = new global::YFex.Validation.ProfileId({Parser.Literal(vm.DefaultProfile)});");
        sb.Close();
        sb.Line();
    }

    // ── Setter hooks (declared by YFex.State.Generator) ─────────────────────────

    private static void EmitHooks(Sb sb, TypeModel m, VmModel vm)
    {
        var byName = Pairs(m).ToDictionary(p => p.Mem.Name, p => p);
        foreach (var (mem, v) in Pairs(m))
        {
            if (!v.HasHook) continue;
            var lines = new List<string>();
            bool change = v.Trigger == 0;
            if (change && IsValidated(mem, v)) lines.Add($"__RunField_{mem.Name}(__bag.Profile, true);");
            foreach (string dep in v.WhenDependents)
                if (byName.TryGetValue(dep, out var d) && d.Vm.Trigger == 0 && IsValidated(d.Mem, d.Vm))
                    lines.Add($"__RunField_{dep}(__bag.Profile, true);");
            if (change && v.InvariantMask != 0) lines.Add($"__RunInvariants({Hex(v.InvariantMask)});");
            if (v.ConstraintsFrom) lines.Add($"__ApplyDecision_{mem.Name}(value);");
            if (lines.Count == 0 && vm.Contracts.IsEmpty) continue;

            sb.Line($"partial void __OnValidate_{mem.Name}(in {v.TypeFqn} value)");
            sb.Open();
            sb.Line($"ValidationIfCreated?.ClearStale({Parser.Literal(mem.Name)}); // server / submit verdicts are stale after an edit");
            if (lines.Count > 0)
            {
                sb.Line("var __bag = Validation;");
                foreach (string l in lines) sb.Line(l);
            }
            sb.Close();
            sb.Line();

            if (v.ConstraintsFrom)
            {
                // 07 §9.3: the decision's violations (Requested checks, Deny/Warn; paths = situation field names = VM
                // property names) replace the previous decision's in the bag; controls re-read Min/Max/Options.
                sb.Line($"private void __ApplyDecision_{mem.Name}({v.TypeFqn} value)");
                sb.Open();
                sb.Line("Validation.ReplaceAll(global::YFex.Validation.ViolationSource.Rule, 0, value is null");
                sb.Line("    ? default(global::System.ReadOnlySpan<global::YFex.Validation.Violation>) : value.Violations.AsSpan());");
                sb.Line("__vConstraintsChanged?.Invoke(\"\");");
                sb.Close();
                sb.Line();
            }
        }
    }

    // ── Field runners: own + borrowed + legacy rules for the CURRENT value ──────

    private static void EmitFieldRunners(Sb sb, TypeModel m, VmModel vm)
    {
        foreach (var (mem, v) in Pairs(m))
        {
            if (!IsValidated(mem, v)) continue;
            string path = $"{m.FieldsClass}.{mem.Name}";
            string lit = Parser.Literal(mem.Name);

            sb.Line($"private void __RunField_{mem.Name}(global::YFex.Validation.ProfileId __profile, bool __startAsync)");
            sb.Open();
            sb.Line("var __bag = Validation;");
            sb.Line($"using var __scope = {W}.Begin(out var w);");
            sb.Line("bool __ok = true;");
            // Borrowed (contract) rules first: the contract is the authority; own rules add UI-only checks.
            foreach (var b in v.Borrowed)
            {
                string guard = ProfileGuard(b.Profile);
                sb.Line($"if (__ok{(guard.Length > 0 ? " && " + guard : "")}) __ok = {b.RulesClassFqn}.Check(this.{mem.Name}, ref w, in {path}, __profile);");
            }
            if (NeedsMemberMethod(mem))
                sb.Line($"if (__ok) __ok = __Validate_{mem.Name}(this, ref w, __profile);");
            else if (!mem.Rules.IsEmpty)
                sb.Line($"if (__ok) __ok = {m.RulesClass}.{mem.Name}.Check(this.{mem.Name}, ref w, in {path}, __profile);");
            foreach (string legacy in v.LegacySync)
                sb.Line($"if (__ok) __ok = global::YFex.State.Validation.LegacyValidation.Add({legacy}.Validate(this.{mem.Name}), ref w, in {path});");
            sb.Line($"__bag.Replace({lit}, {Source}.Field, {Bag}.FieldOwner, ref w);");
            if (HasAsync(mem, v))
            {
                // Async runs only when the sync chain passed; otherwise an in-flight check is invalidated.
                sb.Line($"if (w.HasErrors) __bag.CancelAsync({lit});");
                sb.Line($"else if (__startAsync) _ = __RunAsync_{mem.Name}(this.{mem.Name});");
            }
            sb.Close();
            sb.Line();
        }
    }

    // ── Async runners: versioned, cancellable, debounced (07 §6.3) ──────────────

    private static void EmitAsyncRunners(Sb sb, TypeModel m, VmModel vm)
    {
        foreach (var (mem, v) in Pairs(m))
        {
            if (!HasAsync(mem, v)) continue;
            string path = $"{m.FieldsClass}.{mem.Name}";
            string lit = Parser.Literal(mem.Name);

            sb.Line("/// <summary>One async check per value: a newer value cancels this one; a stale result never lands.");
            sb.Line("/// Continuations resume on the captured SynchronizationContext (UI thread) — faults go to OnAsyncValidationFaulted.</summary>");
            sb.Line($"private async global::System.Threading.Tasks.Task __RunAsync_{mem.Name}({v.TypeFqn} value)");
            sb.Open();
            sb.Line("var __bag = Validation;");
            sb.Line($"var __t = __bag.BeginAsync({lit});");
            sb.Line("try");
            sb.Open();
            if (v.DebounceMs > 0)
                sb.Line($"await global::System.Threading.Tasks.Task.Delay({v.DebounceMs}, __t.Token).ConfigureAwait(true);");
            sb.Line($"{Violation}? __v = null;");
            foreach (var r in mem.AsyncRules)
            {
                string arg, guard;
                if (mem.IsNullableValue && r.UnwrapNullable) { guard = "value.HasValue"; arg = "value.GetValueOrDefault()"; }
                else if (mem.IsReferenceType) { guard = "value is not null"; arg = "value"; }
                else { guard = "true"; arg = "value"; }
                sb.Line($"if (__v is null && {guard}");
                sb.Line($"    && !await {r.RuleTypeFqn}.IsValidAsync({arg}, ValidationServices, __t.Token).ConfigureAwait(true))");
                sb.Line($"    __v = new {Violation}(in {path}, {r.CodeExpr}, {r.SeverityExpr});");
            }
            for (int i = 0; i < v.LegacyAsync.Length; i++)
            {
                sb.Line("if (__v is null)");
                sb.Open();
                sb.Line($"var __r{i} = await {v.LegacyAsync[i]}.ValidateAsync(value, __t.Token).ConfigureAwait(true);");
                sb.Line($"if (!__r{i}.IsSuccess) __v = global::YFex.State.Validation.LegacyValidation.ToViolation(in __r{i}, in {path});");
                sb.Close();
            }
            sb.Line($"if (__v is {{ }} __f) __bag.CompleteAsync(in __t, new {VSpan}(in __f));");
            sb.Line($"else __bag.CompleteAsync(in __t, default({VSpan}));");
            sb.Close();
            sb.Line("catch (global::System.OperationCanceledException) when (__t.Token.IsCancellationRequested)");
            sb.Open();
            sb.Line("// superseded by a newer value");
            sb.Close();
            sb.Line("catch (global::System.Exception __ex)");
            sb.Open();
            sb.Line($"if (__bag.CompleteAsync(in __t, default({VSpan}))) OnAsyncValidationFaulted({lit}, __ex);");
            sb.Close();
            sb.Close();
            sb.Line();
        }
    }

    // ── Invariants on instances: re-run only those reading the changed member ──

    private static void EmitVmInvariants(Sb sb, TypeModel m, VmModel vm)
    {
        if (m.Invariants.IsEmpty) return;
        bool anyHook = vm.Members.Any(x => x.HasHook);

        sb.Line("private ulong __vPendingInvariants;");
        sb.Line();
        sb.Line("/// <summary>Runs the invariants in <paramref name=\"mask\"/>; inside BeginUpdate() they are coalesced into one run at scope end.</summary>");
        sb.Line("private void __RunInvariants(ulong mask)");
        sb.Open();
        sb.Line("if (IsInUpdate) { __vPendingInvariants |= mask; return; }");
        sb.Line("var __bag = Validation;");
        for (int k = 0; k < m.Invariants.Length && k < 64; k++)
            sb.Line($"if ((mask & {Hex(1UL << k)}) != 0) __RunInvariant_{m.Invariants[k].MethodName}(__bag);");
        sb.Close();
        sb.Line();

        if (anyHook)
        {
            sb.Line("partial void __OnBatchValidated()");
            sb.Open();
            sb.Line("ulong __m = __vPendingInvariants;");
            sb.Line("if (__m == 0) return;");
            sb.Line("__vPendingInvariants = 0;");
            sb.Line("__RunInvariants(__m);");
            sb.Close();
            sb.Line();
        }

        foreach (var inv in m.Invariants)
        {
            sb.Line($"private void __RunInvariant_{inv.MethodName}({Bag} __bag)");
            sb.Open();
            sb.Line($"using var __scope = {W}.Begin(out var w);");
            // Skip (and clear) when an input fails its own field rules — avoids noise; its own output doesn't count.
            var gates = inv.ReadsAll ? new List<string>() : inv.Reads.Select(r => $"!__bag.HasFieldErrorsFor({Parser.Literal(r)})").ToList();
            if (gates.Count > 0) sb.Line($"if ({string.Join(" && ", gates)})");
            sb.Open();
            sb.Line($"w.CurrentOrigin = new global::YFex.Validation.ViolationOrigin({Source}.Invariant, {m.InvariantIdsClass}.{inv.MethodName});");
            sb.Line(inv.IsStatic ? $"{inv.MethodName}(this, ref w);" : $"{inv.MethodName}(ref w);");
            sb.Close();
            sb.Line($"__bag.ReplaceAll({Source}.Invariant, {m.InvariantIdsClass}.{inv.MethodName}, ref w);");
            sb.Close();
            sb.Line();
        }
    }

    // ── IValidationSource (explicit) + virtual chain for derived view models ───

    private static void EmitValidationSource(Sb sb, TypeModel m, VmModel vm)
    {
        string mod = vm.BaseHasValidation ? "override" : "virtual";

        // Constraints: own merged with borrowed (most restrictive), computed once.
        var withConstraints = new List<string>();
        foreach (var (mem, v) in Pairs(m))
        {
            var parts = new List<string>();
            foreach (var b in v.Borrowed) parts.Add($"{b.RulesClassFqn}.Constraints");
            if (!mem.Rules.IsEmpty) parts.Add($"{m.RulesClass}.{mem.Name}.Constraints");
            if (parts.Count == 0) continue;
            string expr = parts[0];
            for (int i = 1; i < parts.Count; i++) expr = $"{expr}.Merge({parts[i]})";
            sb.Line($"private static readonly {FC} __Constraints_{mem.Name} = {expr};");
            withConstraints.Add(mem.Name);
        }
        if (withConstraints.Count > 0) sb.Line();

        // [ConstraintsFrom]: static constraints merged (most restrictive) with the current decision's for the same name.
        var decisions = Pairs(m).Where(p => p.Vm.ConstraintsFrom).Select(p => p.Mem.Name).ToList();
        if (decisions.Count > 0)
        {
            sb.Line($"protected {mod} bool __vTryGetConstraints({CharSpan} path, out {FC} constraints)");
            sb.Open();
            sb.Line("bool __has = __StaticConstraints(path, out constraints);");
            for (int i = 0; i < decisions.Count; i++)
            {
                sb.Line($"if ({decisions[i]} is {{ }} __d{i} && __d{i}.TryGetConstraints(path, out var __dyn{i}))");
                sb.Open();
                sb.Line($"constraints = __has ? constraints.Merge(__dyn{i}) : __dyn{i};");
                sb.Line("__has = true;");
                sb.Close();
            }
            sb.Line("return __has;");
            sb.Close();
            sb.Line();
            sb.Line($"private bool __StaticConstraints({CharSpan} path, out {FC} constraints)");
        }
        else sb.Line($"protected {mod} bool __vTryGetConstraints({CharSpan} path, out {FC} constraints)");
        sb.Open();
        if (withConstraints.Count > 0)
        {
            sb.Line("switch (path)");
            sb.Open();
            foreach (string n in withConstraints)
                sb.Line($"case {Parser.Literal(n)}: constraints = __Constraints_{n}; return true;");
            sb.Close();
        }
        if (vm.BaseHasValidation) sb.Line("return base.__vTryGetConstraints(path, out constraints);");
        else
        {
            sb.Line("constraints = default;");
            sb.Line("return false;");
        }
        sb.Close();
        sb.Line();

        // Touch: mark touched; Commit-trigger members validate now.
        sb.Line($"protected {mod} bool __vTouch({CharSpan} path)");
        sb.Open();
        sb.Line("switch (path)");
        sb.Open();
        foreach (var (mem, v) in Pairs(m))
        {
            string lit = Parser.Literal(mem.Name);
            if (v.Trigger == 1 && (IsValidated(mem, v) || v.InvariantMask != 0))
            {
                sb.Line($"case {lit}:");
                sb.Open();
                sb.Line($"Validation.Touch({lit});");
                if (IsValidated(mem, v)) sb.Line($"__RunField_{mem.Name}(Validation.Profile, true);");
                if (v.InvariantMask != 0) sb.Line($"__RunInvariants({Hex(v.InvariantMask)});");
                sb.Line("return true;");
                sb.Close();
            }
            else
            {
                sb.Line($"case {lit}: Validation.Touch({lit}); return true;");
            }
        }
        sb.Close();
        sb.Line(vm.BaseHasValidation ? "return base.__vTouch(path);" : "return false;");
        sb.Close();
        sb.Line();

        const string I = "global::YFex.Validation.IValidationSource";
        sb.Line($"bool {I}.TryGetConstraints({CharSpan} path, out {FC} constraints) => __vTryGetConstraints(path, out constraints);");
        sb.Line($"global::YFex.Validation.ViolationList {I}.GetVisibleViolations({CharSpan} path) => ValidationIfCreated?.GetVisible(path) ?? default;");
        sb.Line($"global::YFex.Validation.FieldStatus {I}.GetStatus({CharSpan} path) => ValidationIfCreated?.GetStatus(path) ?? global::YFex.Validation.FieldStatus.Pristine;");
        sb.Line($"void {I}.Touch({CharSpan} path) {{ if (!__vTouch(path)) Validation.Touch(path); }}");
        sb.Line($"event global::System.Action<string>? {I}.ViolationsChanged");
        sb.Open();
        sb.Line("add => Validation.ValidationChanged += value;");
        sb.Line("remove => Validation.ValidationChanged -= value;");
        sb.Close();
        sb.Line("// Raised when a rules decision changes the dynamic constraints (Phase 4, [ConstraintsFrom]).");
        sb.Line("private global::System.Action<string>? __vConstraintsChanged;");
        sb.Line($"event global::System.Action<string>? {I}.ConstraintsChanged");
        sb.Open();
        sb.Line("add => __vConstraintsChanged += value;");
        sb.Line("remove => __vConstraintsChanged -= value;");
        sb.Close();
        sb.Line();
    }

    // ── Submit validation ───────────────────────────────────────────────────────

    private static void EmitValidateAll(Sb sb, TypeModel m, VmModel vm)
    {
        if (!vm.BaseHasValidation)
        {
            sb.Line("/// <summary>");
            sb.Line("/// Submit validation: every member rule (own + borrowed), every invariant, then each active contract's full");
            sb.Line("/// Validate on <c>ToX()</c> (contract invariants, When rules) remapped to VM paths. Marks submit attempted,");
            sb.Line("/// so AfterTouched/AfterSubmit errors become visible. Async rules keep their last result (not re-run).");
            sb.Line("/// </summary>");
            sb.Line("/// <param name=\"profile\">Strictness profile; null = the bag's active profile.</param>");
            sb.Line("public global::YFex.Validation.ValidationResult ValidateAll(string? profile = null)");
            sb.Open();
            sb.Line("var __bag = Validation;");
            sb.Line("var __profile = profile is null ? __bag.Profile : new global::YFex.Validation.ProfileId(profile);");
            sb.Line("__bag.MarkSubmitAttempted();");
            sb.Line("__vValidateAll(__profile);");
            sb.Line("return __bag.ToResult();");
            sb.Close();
            sb.Line();
        }

        sb.Line($"protected {(vm.BaseHasValidation ? "override" : "virtual")} void __vValidateAll(global::YFex.Validation.ProfileId __profile)");
        sb.Open();
        if (vm.BaseHasValidation) sb.Line("base.__vValidateAll(__profile);");
        sb.Line("var __bag = Validation;");
        foreach (var (mem, v) in Pairs(m))
            if (IsValidated(mem, v)) sb.Line($"__RunField_{mem.Name}(__profile, false);");
        foreach (var inv in m.Invariants)
            sb.Line($"__RunInvariant_{inv.MethodName}(__bag);");
        foreach (var c in vm.Contracts)
        {
            if (!c.IsValidatable) continue;   // ToX() always exists: generated, partial (user body) or user-written
            string owner = $"(ushort)({Bag}.SubmitOwnerBase + {c.Index})";
            string guard = ProfileGuard(c.Profile);
            sb.Line(guard.Length > 0 ? $"if ({guard})" : "");
            sb.Open();
            sb.Line($"var __c{c.Index} = {c.ToMethodName}();");
            sb.Line($"using var __s{c.Index} = {W}.Begin(out var __w{c.Index});");
            sb.Line($"{c.Fqn}.Validate(in __c{c.Index}, ref __w{c.Index}, __profile);");
            sb.Line($"var __map{c.Index} = new __PathMap_{c.Index}();");
            sb.Line($"__bag.ReplaceSubmitResult({owner}, __w{c.Index}.AsSpan(), ref __map{c.Index});");
            sb.Close();
            if (guard.Length > 0) sb.Line($"else __bag.ReplaceAll({Source}.Field, {owner}, default({VSpan}));");
        }
        sb.Close();
        sb.Line();
    }

    // ── Contracts: path maps, ApplyServer<T>, ToX() ─────────────────────────────

    private static void EmitContracts(Sb sb, TypeModel m, VmModel vm)
    {
        if (vm.Contracts.IsEmpty) return;

        foreach (var c in vm.Contracts)
        {
            sb.Line($"/// <summary>{c.ShortName} path ↔ view-model path (server violations, submit validation).</summary>");
            sb.Line($"private readonly struct __PathMap_{c.Index} : global::YFex.Validation.IPathMap");
            sb.Open();
            sb.Line($"public bool TryMap(in {FP} from, out {FP} to)");
            sb.Open();
            if (!c.PathMap.IsEmpty)
            {
                sb.Line("if (from.Indices.Count == 0)");
                sb.Open();
                sb.Line("switch (from.Template)");
                sb.Open();
                foreach (var e in c.PathMap)
                    sb.Line($"case {Parser.Literal(e.ContractTemplate)}: to = {m.FieldsClass}.{e.VmMember}; return true;");
                sb.Close();
                sb.Close();
            }
            sb.Line("to = default;");
            sb.Line("return false;   // unmapped → form-level summary");
            sb.Close();
            sb.Close();
            sb.Line();

            if (c.ToExpr is not null)
            {
                sb.Line($"/// <summary>Builds the {c.ShortName} from this view model (mapped members).</summary>");
                sb.Line($"public {c.Fqn} {c.ToMethodName}() => {c.ToExpr};");
                sb.Line();
            }
            else if (c.EmitToDeclaration)
            {
                sb.Line($"/// <summary>Builds the {c.ShortName} — implement it: not every required member is mapped (YFV0020).</summary>");
                sb.Line($"public partial {c.Fqn} {c.ToMethodName}();");
                sb.Line();
            }
        }

        sb.Line("/// <summary>");
        sb.Line("/// Puts a server result for <typeparamref name=\"TContract\"/> on the fields (Source = Server, always visible):");
        sb.Line("/// contract paths are mapped to view-model paths, unmapped ones go to the form-level summary. A server");
        sb.Line("/// violation is cleared the next time its property changes.");
        sb.Line("/// </summary>");
        sb.Line("public global::YFex.State.ServerOutcome ApplyServer<TContract>(in global::YFex.Validation.ValidationResult result)");
        sb.Open();
        foreach (var c in vm.Contracts)
        {
            sb.Line($"if (typeof(TContract) == typeof({c.Fqn}))");
            sb.Open();
            sb.Line($"var __m = new __PathMap_{c.Index}();");
            sb.Line("return Validation.ApplyServer(result.MapPaths(ref __m));");
            sb.Close();
        }
        sb.Line(vm.BaseHasContracts ? "return base.ApplyServer<TContract>(in result);" : "return Validation.ApplyServer(in result);");
        sb.Close();
        sb.Line();

        if (vm.HasCqrs) EmitCqrsApplyServer(sb, vm.BaseHasContracts ? "new " : "");
    }

    // YFex.State must not reference YFex.Cqrs, so these overloads exist only in compilations that do (07 §7):
    // queued → Queued; ValidationProblem → violations mapped onto the fields → Invalid; any other error → one
    // form-level server violation (code "server.<type>", detail = message) → Failed; success → server violations cleared → Ok.
    private static void EmitCqrsApplyServer(Sb sb, string newMod)
    {
        const string SO = "global::YFex.State.ServerOutcome";
        const string VR = "global::YFex.Validation.ValidationResult";
        const string Cqrs = "global::YFex.Cqrs";

        sb.Line("/// <summary>Applies a command result for <typeparamref name=\"TContract\"/> (see <c>ApplyServer&lt;TContract&gt;(ValidationResult)</c>).</summary>");
        sb.Line($"public {newMod}{SO} ApplyServer<TContract, TResult>(in {Cqrs}.QueueableResult<TResult> result)");
        sb.Open();
        sb.Line($"if (result.IsQueued) return {SO}.Queued;");
        sb.Line($"return result.TryGetError(out var __e) ? __ApplyServerError<TContract>(in __e) : ApplyServer<TContract>({VR}.Valid);");
        sb.Close();
        sb.Line();

        sb.Line("/// <summary>Applies a void command result for <typeparamref name=\"TContract\"/>.</summary>");
        sb.Line($"public {newMod}{SO} ApplyServer<TContract>(in {Cqrs}.QueueableResult result)");
        sb.Open();
        sb.Line($"if (result.IsQueued) return {SO}.Queued;");
