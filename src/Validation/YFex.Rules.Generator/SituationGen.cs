using System.Collections.Generic;
using System.Linq;
using System.Text;
using System.Threading;
using Microsoft.CodeAnalysis;

namespace YFex.Rules.Generator;

/// <summary>[Situation] → ISituation&lt;T&gt; implementation (04 §1.3).</summary>
internal static class SituationGen
{
    public static SituationModel? Transform(GeneratorAttributeSyntaxContext ctx, CancellationToken ct)
    {
        if (ctx.TargetSymbol is not INamedTypeSymbol type) return null;
        var diags = new List<DiagnosticInfo>();
        var loc = type.Locations.FirstOrDefault();
        if (!Names.IsPartial(type)) diags.Add(DiagnosticInfo.Create("YFR0001", loc, type.Name));

        string schemaName = ctx.Attributes[0].ConstructorArguments.FirstOrDefault().Value as string ?? type.Name;
        var props = Shapes.FieldsOf(type, out bool primary);
        var fields = new List<SituationFieldModel>();
        int effectiveDate = 0, lines = 0, tiers = 0;
        foreach (var p in props)
        {
            ct.ThrowIfCancellationRequested();
            var c = Shapes.Classify(p.Type);
            if (!c.Supported)
            {
                diags.Add(DiagnosticInfo.Create("YFR0002", p.Locations.FirstOrDefault() ?? loc, p.Name, type.Name, p.Type.ToDisplayString()));
                continue;
            }
            string role = "Normal";
            int tier = 0;
            if (c.Shape == FieldShape.Lines) { role = "Lines"; lines++; }
            else if (Names.Find(p, Names.Derived) is not null) role = "Derived";
            else if (Names.Find(p, Names.EffectiveDate) is not null)
            {
                role = "EffectiveDate";
                effectiveDate++;
                if (c.Kind is not ("Date" or "DateTime") || c.IsNullable)
                    diags.Add(DiagnosticInfo.Create("YFR0003", p.Locations.FirstOrDefault(), type.Name, p.Name + " is not DateOnly/DateTime"));
            }
            else if (Names.Find(p, Names.RuleTier) is not null)
            {
                role = "Tier";
                tier = ++tiers;
                if (tier == 5) diags.Add(DiagnosticInfo.Create("YFR0007", p.Locations.FirstOrDefault() ?? loc, type.Name));
            }
            else if (Names.Find(p, Names.Requested) is not null) role = "Requested";
            bool exposed = Names.Find(p, Names.Exposed) is not { } ea || ea.ConstructorArguments.FirstOrDefault().Value is not false;

            fields.Add(new SituationFieldModel(p.Name, Names.Of(p.Type), c.ValueTypeFqn, c.InnerMember, c.Shape, c.Kind, role, tier,
                exposed, c.IsNullable, c.IsReferenceNullable, new EquatableArray<EnumMemberModel>(c.EnumMembers), c.LineTypeFqn));
        }
        if (effectiveDate > 1) diags.Add(DiagnosticInfo.Create("YFR0003", loc, type.Name, "found " + effectiveDate));
        if (lines > 1) diags.Add(DiagnosticInfo.Create("YFR0004", loc, type.Name));
        if (fields.Count > 64) diags.Add(DiagnosticInfo.Create("YFR0005", loc, type.Name, fields.Count.ToString()));
        if (!primary && !HasFieldConstructor(type, fields)) diags.Add(DiagnosticInfo.Create("YFR0006", loc, type.Name));

        return new SituationModel(Names.Namespace(type), type.Name, Names.Of(type), Names.Containing(type), Names.Keyword(type).Replace("static ", ""),
            type.IsReadOnly, schemaName, new EquatableArray<SituationFieldModel>(fields.ToArray()), primary,
            new EquatableArray<DiagnosticInfo>(diags.ToArray()));
    }

    private static bool HasFieldConstructor(INamedTypeSymbol type, List<SituationFieldModel> fields)
    {
        var stored = fields.Where(f => f.Role != "Derived").ToArray();
        return type.InstanceConstructors.Any(c => c.Parameters.Length == stored.Length
            && c.Parameters.Select(p => p.Name).SequenceEqual(stored.Select(f => f.Name), System.StringComparer.OrdinalIgnoreCase));
    }

    public static void Emit(SourceProductionContext spc, SituationModel m)
    {
        foreach (var d in m.Diagnostics) if (d.Id is "YFR0001" or "YFR0002" or "YFR0006") return; // uncompilable: report only
        var sb = new StringBuilder();
        sb.AppendLine("// <auto-generated/> YFex.Rules.Generator — situation");
        sb.AppendLine("#nullable enable");
        sb.AppendLine("#pragma warning disable CS1591");
        if (m.Namespace.Length > 0) sb.Append("namespace ").Append(m.Namespace).AppendLine(";");
        foreach (var c in m.Containing) sb.Append("partial ").Append(c.Keyword.Replace("static ", "")).Append(' ').Append(c.Name).AppendLine(" {");

        string t = m.FullyQualified;
        var f = m.Fields;
        int linesIdx = m.LinesIndex;
        var linesField = linesIdx >= 0 ? f[linesIdx] : null;

        sb.Append("partial ").Append(m.Keyword).Append(' ').Append(m.TypeName).Append(" : global::YFex.Rules.ISituation<").Append(t).AppendLine(">");
        sb.AppendLine("{");

        // Field handles + constant ids (the constants let other assemblies' generators bind by name).
        sb.AppendLine("    /// <summary>Typed field handles (directives, tables, bindings).</summary>");
        sb.AppendLine("    public static class Fields");
        sb.AppendLine("    {");
        for (int i = 0; i < f.Length; i++)
        {
            if (f[i].Shape == FieldShape.Lines) continue;
            sb.Append("        public static readonly global::YFex.Rules.SituationField<").Append(t).Append(", ").Append(f[i].TypeFqn)
              .Append("> ").Append(f[i].Name).Append(" = new(").Append(i).Append(", ").Append(Names.Literal(f[i].Name))
              .Append(", ").Append(Shapes.RawTypeOf(f[i].Kind)).AppendLine(");");
        }
        sb.AppendLine("    }");
        sb.AppendLine();
        sb.AppendLine("    /// <summary>Field ids (constants — read by generators of other assemblies).</summary>");
        sb.AppendLine("    public static class FieldIds");
        sb.AppendLine("    {");
        for (int i = 0; i < f.Length; i++) sb.Append("        public const ushort ").Append(f[i].Name).Append(" = ").Append(i).AppendLine(";");
        sb.AppendLine("    }");
        sb.AppendLine();

        // Schema
        sb.Append("    public static global::YFex.Rules.SituationSchema Schema { get; } = new(").Append(Names.Literal(m.SchemaName)).AppendLine(",");
        sb.AppendLine("    [");
        for (int i = 0; i < f.Length; i++)
        {
            var x = f[i];
            sb.Append("        new(").Append(i).Append(", ").Append(Names.Literal(x.Name)).Append(", ").Append(Shapes.RawTypeOf(x.Kind))
              .Append(", global::YFex.Rules.FieldRole.").Append(x.Role);
            if (x.Tier > 0) sb.Append(", tier: ").Append(x.Tier);
            if (!x.Exposed) sb.Append(", exposed: false");
            if (x.EnumMembers.Length > 0)
            {
                sb.Append(", enumOptions: [");
                for (int k = 0; k < x.EnumMembers.Length; k++)
                {
                    var em = x.EnumMembers[k];
                    if (k > 0) sb.Append(", ");
                    sb.Append("new(").Append(em.Value).Append("L, ").Append(Names.Literal(em.Code)).Append(", ").Append(Names.Literal(em.Name)).Append(')');
                }
                sb.Append(']');
            }
            if (x.Shape == FieldShape.Lines) sb.Append(", lineSchema: ").Append(x.LineTypeFqn).Append(".Schema");
            sb.Append(", clrType: ").Append(Names.Literal(x.TypeFqn.Replace("global::", "")));
            sb.AppendLine("),");
        }
        sb.AppendLine("    ]);");
        sb.AppendLine();

        // Read
        sb.Append("    public static global::YFex.RawValue Read(in ").Append(t).AppendLine(" s, ushort fieldId) => fieldId switch");
        sb.AppendLine("    {");
        for (int i = 0; i < f.Length; i++)
        {
            if (f[i].Shape == FieldShape.Lines) continue;
            sb.Append("        ").Append(i).Append(" => ").Append(Raw(f[i], "s." + f[i].Name)).AppendLine(",");
        }
        sb.AppendLine("        _ => default,");
        sb.AppendLine("    };");
        sb.AppendLine();

        // TryGetFieldId
        sb.AppendLine("    public static bool TryGetFieldId(global::System.ReadOnlySpan<char> name, out ushort id)");
        sb.AppendLine("    {");
        sb.AppendLine("        switch (name)");
        sb.AppendLine("        {");
        for (int i = 0; i < f.Length; i++)
            sb.Append("            case ").Append(Names.Literal(f[i].Name)).Append(": id = ").Append(i).AppendLine("; return true;");
        sb.AppendLine("        }");
        sb.AppendLine("        id = 0;");
        sb.AppendLine("        return false;");
        sb.AppendLine("    }");
        sb.AppendLine();

        // Lines
        if (linesField is not null)
        {
            string lm = "s." + linesField.Name;
            sb.Append("    public static int LineCount(in ").Append(t).Append(" s) => ").Append(lm).Append(".IsDefault ? 0 : ").Append(lm).AppendLine(".Length;");
            sb.Append("    public static global::YFex.RawValue ReadLine(in ").Append(t).Append(" s, int lineIndex, ushort lineFieldId) => ")
              .Append(linesField.LineTypeFqn).Append(".Read(in ").Append(lm).AppendLine(".ItemRef(lineIndex), lineFieldId);");
        }
        else
        {
            sb.Append("    public static int LineCount(in ").Append(t).AppendLine(" s) => 0;");
            sb.Append("    public static global::YFex.RawValue ReadLine(in ").Append(t).AppendLine(" s, int lineIndex, ushort lineFieldId) => default;");
        }

        // EffectiveDate / TierPath
        var dateField = f.FirstOrDefault(x => x.Role == "EffectiveDate");
        sb.Append("    public static global::System.DateOnly EffectiveDate(in ").Append(t).Append(" s) => ");
        sb.AppendLine(dateField is null ? "global::System.DateOnly.MaxValue;"
            : dateField.Kind == "DateTime" ? $"global::System.DateOnly.FromDateTime(s.{dateField.Name});" : $"s.{dateField.Name};");
        var tierFields = f.Where(x => x.Tier > 0).OrderBy(x => x.Tier).ToArray();
        sb.Append("    public static global::YFex.Rules.RuleTierPath TierPath(in ").Append(t).Append(" s) => ");
        if (tierFields.Length == 0) sb.AppendLine("global::YFex.Rules.RuleTierPath.Code;");
        else sb.Append("global::YFex.Rules.RuleTierPath.Of(").Append(string.Join(", ", tierFields.Select(x => Raw(x, "s." + x.Name)))).AppendLine(");");
        sb.AppendLine();

        // AppendTo / Serialize / Deserialize
        sb.Append("    public static void AppendTo(in ").Append(t).AppendLine(" s, ref global::YFex.Helpers.StableHash64 hash)");
        sb.AppendLine("    {");
        for (int i = 0; i < f.Length; i++)
        {
            var x = f[i];
            if (x.Role == "Derived") continue;
            if (x.Shape == FieldShape.Lines)
            {
                sb.Append("        { int n = LineCount(in s); hash.Append(n); for (int i = 0; i < n; i++) ").Append(x.LineTypeFqn)
                  .Append(".AppendTo(in s.").Append(x.Name).AppendLine(".ItemRef(i), ref hash); }");
            }
            else sb.Append("        ").Append(Raw(x, "s." + x.Name)).AppendLine(".AppendTo(ref hash);");
        }
        sb.AppendLine("    }");
        sb.AppendLine();
        sb.Append("    public static void Serialize(in ").Append(t).AppendLine(" s, ref global::YFex.Rules.SituationWriter w)");
        sb.AppendLine("    {");
        foreach (var x in f)
        {
            if (x.Role == "Derived") continue;
            if (x.Shape == FieldShape.Lines)
                sb.Append("        { int n = LineCount(in s); w.WriteCount(n); for (int i = 0; i < n; i++) ").Append(x.LineTypeFqn)
                  .Append(".Serialize(in s.").Append(x.Name).AppendLine(".ItemRef(i), ref w); }");
            else sb.Append("        w.Write(").Append(Raw(x, "s." + x.Name)).AppendLine(");");
        }
        sb.AppendLine("    }");
        sb.AppendLine();
        sb.Append("    public static ").Append(t).AppendLine(" Deserialize(ref global::YFex.Rules.SituationReader r)");
        sb.AppendLine("    {");
        var args = new List<string>();
        int li = 0;
        foreach (var x in f)
        {
            if (x.Role == "Derived") continue;
            string v = "__f" + li++;
            if (x.Shape == FieldShape.Lines)
            {
                sb.Append("        int ").Append(v).AppendLine("n = r.ReadCount();");
                sb.Append("        var ").Append(v).Append(" = global::System.Collections.Immutable.ImmutableArray.CreateBuilder<").Append(x.LineTypeFqn)
                  .Append(">(").Append(v).AppendLine("n);");
                sb.Append("        for (int i = 0; i < ").Append(v).Append("n; i++) ").Append(v).Append(".Add(").Append(x.LineTypeFqn).AppendLine(".Deserialize(ref r));");
                args.Add(v + ".MoveToImmutable()");
            }
            else
            {
                sb.Append("        var ").Append(v).Append(" = ").Append(ReadExpr(x)).AppendLine(";");
                args.Add(v);
            }
        }
        sb.Append("        return new ").Append(t).Append('(').Append(string.Join(", ", args)).AppendLine(");");
        sb.AppendLine("    }");
        sb.AppendLine();

        // DiffMask
        sb.Append("    public static ulong DiffMask(in ").Append(t).Append(" a, in ").Append(t).AppendLine(" b)");
        sb.AppendLine("    {");
        sb.AppendLine("        ulong m = 0;");
        for (int i = 0; i < f.Length; i++)
        {
            var x = f[i];
            int bit = i < 63 ? i : 63;
            if (x.Shape == FieldShape.Lines)
                sb.Append("        if (!global::System.MemoryExtensions.SequenceEqual(a.").Append(x.Name).Append(".AsSpan(), b.").Append(x.Name)
                  .Append(".AsSpan())) m |= 1UL << ").Append(bit).AppendLine(";");
            else
                sb.Append("        if (!global::System.Collections.Generic.EqualityComparer<").Append(x.TypeFqn).Append(">.Default.Equals(a.").Append(x.Name)
                  .Append(", b.").Append(x.Name).Append(")) m |= 1UL << ").Append(bit).AppendLine(";");
        }
        sb.AppendLine("        return m;");
        sb.AppendLine("    }");
        sb.AppendLine();

        // Type-level conveniences (04 §1.3 names).
        sb.Append("    public static ulong Hash(in ").Append(t).AppendLine(" s) => global::YFex.Rules.Situation.Hash(in s);");
        sb.Append("    public static void WriteTo(in ").Append(t).AppendLine(" s, global::System.Buffers.IBufferWriter<byte> w) => global::YFex.Rules.Situation.WriteTo(in s, w);");
        sb.Append("    public static ").Append(t).Append(" ReadFrom(global::System.ReadOnlySpan<byte> data) => global::YFex.Rules.Situation.ReadFrom<").Append(t).AppendLine(">(data);");
        sb.AppendLine("}");
        foreach (var _ in m.Containing) sb.AppendLine("}");

        spc.AddSource(Hint(m.FullyQualified) + ".Situation.g.cs", sb.ToString());
    }

    /// <summary>RawValue expression for a field read from <paramref name="expr"/>.</summary>
    public static string Raw(SituationFieldModel f, string expr)
        => Shapes.ToRaw(new TypeClass(f.Shape, f.Kind, f.ValueTypeFqn, f.InnerMember, f.IsNullable, f.IsReferenceNullable, [], null, true), expr);

    private static string ReadExpr(SituationFieldModel f)
    {
        string read = f.Shape switch
        {
            FieldShape.Enum => $"r.ReadEnum<{f.ValueTypeFqn}>()",
            FieldShape.WrapperEnum => $"new {Strip(f.TypeFqn)}(r.ReadEnum<{f.ValueTypeFqn}>())",
            FieldShape.Wrapper => $"new {Strip(f.TypeFqn)}(r.Read<{f.ValueTypeFqn}>(){(f.Kind == "Text" ? "!" : "")})",
            _ => f.Kind == "Text" && !f.IsReferenceNullable ? $"r.Read<{f.ValueTypeFqn}>()!" : $"r.Read<{f.ValueTypeFqn}>()",
        };
        if (!f.IsNullable) return read;
        // Nullable<T>: peek by reading the raw value first.
        string inner = f.Shape switch
        {
            FieldShape.Enum => $"__r.TryGetEnum(out {f.ValueTypeFqn} __e) ? __e : default",
            FieldShape.WrapperEnum => $"new {Strip(f.TypeFqn)}(__r.TryGetEnum(out {f.ValueTypeFqn} __e) ? __e : default)",
            FieldShape.Wrapper => $"new {Strip(f.TypeFqn)}(global::YFex.RawValueConvert.To<{f.ValueTypeFqn}>(in __r)!)",
            _ => $"global::YFex.RawValueConvert.To<{f.ValueTypeFqn}>(in __r)",
        };
        return $"((global::System.Func<global::YFex.RawValue, {f.TypeFqn}>)(static __r => __r.IsNone ? null : ({Strip(f.TypeFqn)})({inner})))(r.Read())";
    }

    private static string Strip(string fqn) => fqn.EndsWith("?") ? fqn.Substring(0, fqn.Length - 1) : fqn;

    public static string Hint(string fqn) => fqn.Replace("global::", "").Replace('<', '[').Replace('>', ']');
}
